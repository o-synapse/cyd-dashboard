"""Generate TFT_eSPI smooth-font (.vlw) C arrays from open-source fonts.

Usage: pip install pillow && python tools/make_fonts.py   (writes src/fonts.h)

Uses Inter and Nunito (SIL Open Font License), downloaded from the Google Fonts
repository into tools/fonts/ the first time it runs. src/fonts.h is committed, so
you only need this if you change sizes, weights or characters.
"""
import os
import struct
import urllib.request
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "fonts.h")
FONT_DIR = os.path.join(HERE, "fonts")
SOURCES = {
    "Inter.ttf": "https://raw.githubusercontent.com/google/fonts/main/ofl/inter/Inter%5Bopsz,wght%5D.ttf",
    "Nunito.ttf": "https://raw.githubusercontent.com/google/fonts/main/ofl/nunito/Nunito%5Bwght%5D.ttf",
}


def font_file(name):
    path = os.path.join(FONT_DIR, name)
    if not os.path.exists(path):
        os.makedirs(FONT_DIR, exist_ok=True)
        print("downloading", name)
        urllib.request.urlretrieve(SOURCES[name], path)
    return path


ASCII = "".join(chr(c) for c in range(32, 127)) + "°·"
INTER, NUNITO = "Inter.ttf", "Nunito.ttf"

# name, font file, pixel size, weight, characters
FONTS = [
    ("F_GREET", NUNITO, 37, 800, ASCII),
    ("F_GREET_S", NUNITO, 31, 800, ASCII),
    ("F_TIME", INTER, 64, 500, "0123456789:- "),
    ("F_TEMP", INTER, 45, 300, "0123456789-°CF "),
    ("F_MED", INTER, 18, 500, ASCII),
    ("F_SMALL", INTER, 14, 500, ASCII),
]


def load(name, size, weight):
    f = ImageFont.truetype(font_file(name), size)
    axes = f.get_variation_axes()
    vals = []
    for a in axes:
        n = a["name"].decode() if isinstance(a["name"], bytes) else a["name"]
        if n == "Weight":
            vals.append(weight)
        elif n.lower() == "optical size":
            vals.append(max(a["minimum"], min(a["maximum"], size)))
        else:
            vals.append(a["default"])
    f.set_variation_by_axes(vals)
    return f


def make_vlw(path, size, weight, chars):
    font = load(path, size, weight)
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        adv = round(font.getlength(ch))
        if ch == " ":
            glyphs.append((ord(ch), 0, 0, adv, 0, 0, b""))
            continue
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = r - l, b - t
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
        glyphs.append((ord(ch), h, w, adv, -t, l, img.tobytes()))
    ascent = max(g[4] for g in glyphs)
    descent = max(g[1] - g[4] for g in glyphs)
    out = struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    for code, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", code, h, w, adv, dy, dx, 0)
    for g in glyphs:
        out += g[6]
    return out


def main():
    lines = ["// Generated by tools/make_fonts.py - do not edit", "#pragma once", "#include <pgmspace.h>", ""]
    for name, path, size, weight, chars in FONTS:
        data = make_vlw(path, size, weight, chars)
        lines.append(f"const uint8_t {name}[] PROGMEM = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
        print(f"{name}: {len(data)} bytes")
    with open(OUT, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
